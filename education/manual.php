<?php
/**
 * 担当者マニュアル（ログイン不要）。
 * 研修・勉強会の主催担当者向けに、予定の登録・複製・変更・中止の手順を説明する。
 * トップページ左側の「担当者マニュアル」から開く。印刷して配布してもよい。
 */
define('EDU_APP', true);
$config = require __DIR__ . '/config.php';
require __DIR__ . '/common.php';

edu_layout_header($config, '担当者マニュアル', 'manual');
?>

<div class="panel manual">
  <h2>担当者マニュアル（研修・勉強会の主催担当者の方へ）</h2>
  <p class="lead">
    委員会・本部・部署で研修や勉強会を担当する方は、どなたでもこのサイトに予定を登録できます。
    <strong>ログインは不要</strong>です。登録した予定は管理者（教育委員会 等）が確認・承認したあと、
    全職員が見る「予定一覧」と「カレンダー」に掲載されます。
  </p>
  <div class="actions no-print">
    <a href="new.php" class="btn">＋ 予定を登録する</a>
    <button type="button" class="secondary" onclick="window.print()">このマニュアルを印刷</button>
  </div>

  <h3>全体の流れ</h3>
  <ol class="flow">
    <li><strong>登録</strong>：担当者が「予定を登録」から申請する</li>
    <li><strong>承認</strong>：管理者が内容を確認して承認する（承認待ちの間は一覧に出ません）</li>
    <li><strong>掲載</strong>：予定一覧・カレンダーに表示され、全職員が確認できる</li>
    <li><strong>変更・中止</strong>：必要になったら担当者が自分で変更・中止する</li>
  </ol>

  <h3 id="register">1. 予定を登録する</h3>
  <ol>
    <li>画面上部の <strong>「予定を登録」</strong> を押します。</li>
    <li><strong>研修の内容</strong>：研修名・種別・主催・対象を入力します。
      受講が義務の研修は「必須研修」にチェックを入れてください。
      主催が一覧に無い場合は「その他（下に入力）」を選んで名前を入力します。</li>
    <li><strong>開催形式</strong>を選びます。
      <ul>
        <li><strong>会場で開催</strong>：開催日・開始時刻・終了時刻と <strong>会場</strong>（例: 6階会議室）を入力します。</li>
        <li><strong>オンライン視聴</strong>：<strong>視聴開始日</strong>と<strong>視聴終了日（締切）</strong>、
          <strong>配信方法</strong>（院内受講管理システム（CHATIS）／GAKKEN）を選びます。
          期間内に視聴できなかった場合の扱い（レポート提出先・期限など）は「内容・参加方法など」に書いてください。</li>
      </ul>
    </li>
    <li><strong>担当者</strong>：氏名・所属・内線を入力します（問い合わせ先として表示されます）。</li>
    <li><strong>編集用パスワード</strong>を自分で決めて入力します（4文字以上）。
      後から変更・中止するときに使うので、<strong>登録番号と一緒に控えておいてください</strong>。</li>
    <li><strong>「登録を申請する」</strong> を押すと受付完了です。表示される登録番号（#123 など）を控えてください。</li>
  </ol>

  <h3 id="copy">2. 前回・昨年の研修を複製して登録する</h3>
  <ol>
    <li>「予定を登録」画面の上にある <strong>「過去の研修から複製して登録する」</strong> を開きます。</li>
    <li>研修名や主催で検索し、使いたい研修の <strong>「この内容で登録」</strong> を押します。</li>
    <li>日付以外の内容が入った状態になるので、<strong>日付（視聴期間）を入力</strong>し、
      必要なら研修名（第○回など）を直して申請します。</li>
  </ol>
  <p class="note">予定の詳細画面の「この内容で次回を登録」からも同じように複製できます。</p>

  <h3 id="approve">3. 承認されるまで</h3>
  <ul>
    <li>申請直後は「承認待ち」です。予定一覧・カレンダーにはまだ表示されません。</li>
    <li>管理者が承認すると掲載されます。</li>
    <li>内容に不備があると<strong>「差戻し」</strong>になります。詳細画面に理由が表示されるので、
      「変更・中止」から修正して保存すると、もう一度承認待ちになります。</li>
  </ul>

  <h3 id="edit">4. 日時・内容を変更する</h3>
  <ol>
    <li>予定一覧（またはカレンダー）で自分の研修を開きます。</li>
    <li><strong>「変更・中止（担当者用）」</strong> を押し、<strong>編集用パスワード</strong>を入力します。</li>
    <li>内容を直して <strong>「変更を保存」</strong> を押します。</li>
  </ol>
  <p class="note">掲載中の予定を変更しても掲載は続きます。一覧に「変更あり」と表示され、詳細画面に変更履歴が残ります。</p>

  <h3 id="cancel">5. 中止する・取り下げる</h3>
  <ul>
    <li>「変更・中止（担当者用）」の画面下にある <strong>「中止にする」</strong> を押します。
      一覧・カレンダーには取り消し線付きの「中止」として残ります。</li>
    <li>承認前（承認待ち・差戻し）の予定は <strong>「取り下げる」</strong> で削除できます。</li>
  </ul>

  <h3 id="faq">6. 困ったとき</h3>
  <dl class="detail faq">
    <dt>編集用パスワードを忘れた</dt>
    <dd>管理者（教育委員会 等）に登録番号を伝えて、パスワードの再設定を依頼してください。</dd>
    <dt>主催・会場・配信方法の選択肢に無い</dt>
    <dd>主催は「その他（下に入力）」で入力できます。選択肢そのものを増やしたい場合は管理者に依頼してください。</dd>
    <dt>複数日にわたる研修</dt>
    <dd>会場で開催する研修は、日ごとに登録してください（研修名に「1日目」「2日目」など）。
      オンライン視聴は視聴期間で1件として登録します。</dd>
    <dt>登録した予定が一覧に出ない</dt>
    <dd>承認待ちの可能性があります。しばらく待っても掲載されない場合は管理者にお問い合わせください。</dd>
  </dl>
</div>

<?php edu_layout_footer($config); ?>
